def above(base, accent, upper=False):
    """base letter (five rows) with an accent: one-row accents at y=6, two-row at y=7..6."""
    body = SQ[base] if upper else LOW[base]
    w = len(body[0])
    acc = [a[:w].ljust(w, ".") for a in accent]
    rows = acc + ["." * w] + body
    top = 6 if len(acc) == 1 else 7
    extra = [] if base != "g" else ["####."]
    return (top, rows + extra)

def below(rows, top, tail):
    return (top, rows + [tail])

